    /// <summary>
    /// Canonical live distribution tests: full-quality video renders that genuinely load the worker
    /// nodes (1080p, real sample counts, many frames) across all three engines, driven end-to-end
    /// through the Blender bridge (the exact path the addon uses). Unlike the preview-grade
    /// distribution tests (640×360 / 1 sample), these are heavy enough for the per-node split to
    /// reflect real work — open NODE ASSIGNMENTS in the admin UI to watch the balancing.
    ///
    /// Two kinds of input, per the canonical-test plan:
    ///   - REAL meaningful scenes from blender.org demo files dropped into <c>@Data/</c>
    ///     (cube_diorama, greasepencil-bike) — gitignored, self-skip when absent.
    ///   - ARTIFICIAL self-contained scenes committed under <c>@Data/canonical/</c> (generated by the
    ///     Python scripts in <c>Canonical/</c>) — always present, so the suite has a real animated
    ///     effect to render out of the box and serves as a worked example for plugin authors.
    ///
    /// Output MP4s land under <c>@Output/canonical/&lt;case&gt;/</c> for inspection.
    /// [Explicit] + env-gated on OMNIBUSCLOUD_API_KEY. Long timeout — real multi-frame renders.
    /// </summary>
    [TestFixture]
    [Explicit("Canonical full-quality live distribution workload against the deployed OmnibusCloud instance — watch NODE ASSIGNMENTS in the UI.")]
    [NonParallelizable]
    internal sealed class BridgeCanonicalDistributionTests
    {
        #region Constants

        private static readonly TimeSpan TIMEOUT = TimeSpan.FromMinutes(45);
        private static readonly TimeSpan POLL = TimeSpan.FromSeconds(5);

        #endregion

        #region Fields

        private LiveCloudConnectionService m_connection = null!;

        #endregion

        #region Setup

        [OneTimeSetUp]
        public async Task SetupAsync()
        {
            if (!LiveIntegrationSettings.IsConfigured)
                Assert.Ignore("Live integration skipped: set OMNIBUSCLOUD_API_KEY.");

            using var cts = new CancellationTokenSource(TimeSpan.FromMinutes(2));
            m_connection = new LiveCloudConnectionService(
                LiveIntegrationSettings.ServerUrl,
                LiveIntegrationSettings.IdentityUrl,
                LiveIntegrationSettings.ApiKey!);

            if (!await m_connection.EnsureConnectedAsync(cts.Token))
                Assert.Fail("Could not connect to the deployed OmnibusCloud API.");
        }

        [OneTimeTearDown]
        public async Task TearDownAsync()
        {
            if (m_connection != null)
                await m_connection.DisconnectAsync();
        }

        #endregion

        #region Cases

        public static IEnumerable<TestCaseData> CanonicalCases()
        {
            // caseName, benchmarkFallback, dataRelative, engine, resX, resY, samples, startFrame, endFrame, port

